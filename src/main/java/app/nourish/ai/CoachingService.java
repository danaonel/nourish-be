package app.nourish.ai;

import app.nourish.domain.GoalType;
import app.nourish.domain.Profile;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.stereotype.Service;

import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Optional;

/**
 * "Coach me through this" craving flow (FR-17, FR-25) and pantry-based suggestions
 * (FR-13a). Persona-aware: the RECOVERY goal never uses restriction framing.
 *
 * <p>When Claude is configured, the flow is generated by the model under the
 * persona system prompt; otherwise (and on any error) it falls back to the
 * deterministic templates below, so the feature always works.</p>
 */
@Service
public class CoachingService {

    private static final Logger log = LoggerFactory.getLogger(CoachingService.class);

    private final AnthropicClient anthropic;
    private final ConstraintFilter constraintFilter;
    private final ObjectMapper mapper = new ObjectMapper();

    public CoachingService(AnthropicClient anthropic, ConstraintFilter constraintFilter) {
        this.anthropic = anthropic;
        this.constraintFilter = constraintFilter;
    }

    public record CoachStep(String title, String body) {}

    /** A short guided flow, not a generic push message. */
    public List<CoachStep> cravingFlow(Profile profile, String situation) {
        if (anthropic.isConfigured()) {
            Optional<List<CoachStep>> llm = cravingFlowViaClaude(profile, situation);
            if (llm.isPresent()) return llm.get();
        }
        return cravingFlowLocal(profile, situation);
    }

    private Optional<List<CoachStep>> cravingFlowViaClaude(Profile profile, String situation) {
        StringBuilder user = new StringBuilder();
        user.append("The user is facing a craving or a hard food moment and asked to be coached ")
                .append("through it. Give a SHORT guided flow of 3-4 steps.\n");
        user.append("Return STRICT JSON only: {\"steps\":[{\"title\":\"...\",\"body\":\"...\"}]}\n");
        user.append("Keep each body to one or two sentences, warm and practical.\n\n");
        user.append("User goal: ").append(profile.getGoalType()).append('\n');
        if (situation != null && !situation.isBlank()) {
            user.append("Situation they described: ").append(situation).append('\n');
        }
        if (!profile.getAppetiteCurbingFoods().isEmpty() && profile.getGoalType() != GoalType.RECOVERY) {
            user.append("Foods they told us reliably help: ")
                    .append(String.join(", ", profile.getAppetiteCurbingFoods())).append('\n');
        }

        Optional<String> resp = anthropic.complete(
                PersonaPrompts.systemPromptFor(profile.getGoalType()), user.toString(), 700);
        if (resp.isEmpty()) return Optional.empty();

        try {
            String json = extractJson(resp.get());
            JsonNode steps = mapper.readTree(json).path("steps");
            if (!steps.isArray() || steps.isEmpty()) return Optional.empty();
            List<CoachStep> out = new ArrayList<>();
            for (JsonNode s : steps) {
                String title = s.path("title").asText("").trim();
                String body = s.path("body").asText("").trim();
                if (!title.isEmpty() && !body.isEmpty()) out.add(new CoachStep(title, body));
            }
            return out.isEmpty() ? Optional.empty() : Optional.of(out);
        } catch (Exception e) {
            log.warn("Could not parse Claude craving flow, using local template: {}", e.getMessage());
            return Optional.empty();
        }
    }

    /** Deterministic fallback flow. */
    private List<CoachStep> cravingFlowLocal(Profile profile, String situation) {
        List<CoachStep> steps = new ArrayList<>();
        boolean recovery = profile.getGoalType() == GoalType.RECOVERY;

        steps.add(new CoachStep("Pause", recovery
                ? "Take a slow breath. Whatever you choose next is okay. Let's look at your options together."
                : "Take a slow breath. Cravings peak and pass, usually within about 15 minutes."));

        if (!profile.getAppetiteCurbingFoods().isEmpty() && !recovery) {
            steps.add(new CoachStep("Reach for what works",
                    "You told us these reliably help: " + String.join(", ", profile.getAppetiteCurbingFoods()) + "."));
        }

        if (situation != null && situation.toLowerCase(Locale.ROOT).contains("fridge")) {
            steps.add(new CoachStep("Make something fast",
                    "Even a simple protein + veg from what's on hand beats ordering in. Want a pantry recipe?"));
        }

        steps.add(new CoachStep("Decide with intention", recovery
                ? "Choose the option that helps you stay steady and nourished right now."
                : "Pick the goal-aligned option. You've already done the hard part by pausing."));

        return steps;
    }

    /** FR-13a: suggest something goal-aligned from ingredients on hand. */
    public String pantrySuggestion(Profile profile, List<String> onHand) {
        if (onHand == null || onHand.isEmpty()) {
            return "Add a few ingredients you have and I'll suggest something that fits your goal.";
        }
        String base = String.join(", ", onHand);

        if (anthropic.isConfigured()) {
            String user = "The user has these ingredients on hand: " + base
                    + ".\nSuggest ONE quick meal they can make right now that fits their goal and "
                    + "respects their constraints. Two or three sentences, no preamble.";
            Optional<String> resp = anthropic.complete(
                    PersonaPrompts.systemPromptFor(profile.getGoalType()), user, 400);
            // Hard boundary: if the model's suggestion names an excluded food
            // (allergy / intolerance / ethical), discard it and fall back.
            if (resp.isPresent() && constraintFilter.check(profile, resp.get()).allowed()) {
                return resp.get();
            }
        }

        if (profile.getGoalType() == GoalType.GAIN) {
            return "With " + base + ", build a calorie-dense bowl: combine your protein and carbs, add a healthy fat (oil, nuts, avocado).";
        }
        return "With " + base + ", make a protein-forward plate: lead with your protein, fill half the plate with veg, keep it simple.";
    }

    private String extractJson(String text) {
        int start = text.indexOf('{');
        int end = text.lastIndexOf('}');
        if (start >= 0 && end > start) return text.substring(start, end + 1);
        return text;
    }
}
